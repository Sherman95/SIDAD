import os
from src.tools.bi.provider import BIProvider
from src.models.semantic_model import SemanticProject, ColumnRole
from src.models.dashboard import DashboardPlan

class PowerBIProvider(BIProvider):
    """
    Implementación concreta para Power BI.
    Para el MVP, genera archivos TMDL (Tabular Model Definition Language),
    el formato oficial de Microsoft en texto plano para control de versiones de modelos semánticos.
    """
    def deploy_semantic_model(self, semantic: SemanticProject, output_path: str) -> bool:
        os.makedirs(output_path, exist_ok=True)
        tmdl_path = os.path.join(output_path, "model.tmdl")
        
        with open(tmdl_path, "w", encoding="utf-8") as f:
            f.write("database 'GeneradoPorAgenteSIDAD'\n\n")
            
            for table in semantic.tables:
                f.write(f"table {table.name}\n")
                f.write("  lineageTag: autogenerated\n\n")
                
                for col in table.columns:
                    # Mapeo básico de tipos a DAX
                    dax_type = "string"
                    if col.role == ColumnRole.METRIC: dax_type = "double"
                    elif col.role == ColumnRole.DATE: dax_type = "dateTime"
                    elif col.role == ColumnRole.KEY: dax_type = "int64"
                    
                    f.write(f"  column {col.name}\n")
                    f.write(f"    dataType: {dax_type}\n")
                    f.write(f"    sourceColumn: {col.name}\n")
                    f.write(f"    summarizeBy: {'sum' if col.role == ColumnRole.METRIC else 'none'}\n\n")
                    
            # Medidas DAX propuestas
            for kpi in semantic.kpis:
                if kpi.dax_suggestion:
                    f.write(f"  measure '{kpi.name}' = {kpi.dax_suggestion}\n")
                    f.write(f"    formatString: \"0.00\"\n\n")
                    
        return True

    def deploy_dashboard(self, plan: DashboardPlan, output_path: str) -> bool:
        """
        Para el MVP, guardamos la especificación JSON del reporte.
        En una fase avanzada, esto se traduciría al report.json dentro de un .pbip.
        """
        os.makedirs(output_path, exist_ok=True)
        report_path = os.path.join(output_path, "report_spec.json")
        
        with open(report_path, "w", encoding="utf-8") as f:
            f.write(plan.model_dump_json(indent=2))
            
        return True
